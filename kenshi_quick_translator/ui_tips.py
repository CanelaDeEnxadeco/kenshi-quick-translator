MORE_V076: list[tuple[str, str, str, str, str]] = [(pt, *rest) for _c, _k, pt, *rest in TIPS]


def find_tip(ctx: str, texts, tr=lambda s: s) -> str:
    """
    Dica (em português) para um botão. `texts`: o texto original em português e o atual (talvez já traduzido).
    A janela (ctx) vem primeiro; depois as dicas de qualquer janela. Compara sem atalho e sem “…”.
    """
    cands = {norm(t) for t in texts if t}
    cands.discard("")
    if not cands:
        return ""
    for table in (CONTEXT_TIPS.get(ctx, {}), BUTTON_TIPS):
        for key, tip in table.items():
            if norm(key) in cands or norm(tr(key)) in cands:
                return tip
    return ""
