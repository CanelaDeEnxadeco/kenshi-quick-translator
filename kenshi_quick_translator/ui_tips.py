_SHORTCUT = re.compile(r"\s*\((?:Ctrl|Shift|Alt|F\d+|Esc)[^)]*\)\s*$")


def norm(text: str) -> str:
    """Texto do botão sem ícone no começo, sem atalho nem reticências no fim e com espaços simples."""
    s = " ".join(str(text).split())
    s = _SHORTCUT.sub("", s)
    i = 0
    while i < len(s) and not s[i].isalnum():  # ícone no começo ("▶  ", "⚙  ", "?  ")
        i += 1
    return s[i:].rstrip("… .").strip()


CONTEXT_TIPS: dict[str, dict[str, str]] = {}
BUTTON_TIPS: dict[str, str] = {}
for _ctx, _key, _pt, *_rest in TIPS:
    if _key.startswith("§"):
        continue
    (CONTEXT_TIPS.setdefault(_ctx, {}) if _ctx else BUTTON_TIPS)[_key] = _pt

